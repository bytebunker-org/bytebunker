import { Injectable } from '@nestjs/common';
import type { EntityManager } from '@mikro-orm/postgresql';
import type { JSONSchema7, JSONSchema7Definition } from 'json-schema';
import { PipelineModuleEntity } from '../pipeline-module/entity/pipeline-module.entity.js';
import { PipelineModuleTypeEnum } from '../pipeline-module/type/pipeline-module-type.enum.js';
import type { BlueprintDataDto } from './dto/blueprint-data.dto.js';
import type {
    BlueprintValidationIssueDto,
    BlueprintValidationResultDto,
} from './dto/blueprint-validation-result.dto.js';

/** Handles every module has that are not part of its typed inputs/outputs (execution ordering). */
const SPECIAL_INPUT_HANDLES = new Set(['dependentModules']);
const SPECIAL_OUTPUT_HANDLES = new Set(['success']);
/** execute-code declares extra handles in its constant input. */
const CUSTOM_HANDLE_KEYS = { input: 'customInputParameters', output: 'customOutputParameters' } as const;

interface ModuleSchemas {
    type: PipelineModuleTypeEnum;
    input?: JSONSchema7;
    output?: JSONSchema7;
}

/**
 * Static checks for a blueprint before it is saved or run. Meant for blueprints written by hand or generated by
 * an AI: every problem comes with the node/edge it belongs to and a message that says how to fix it.
 */
@Injectable()
export class PipelineBlueprintValidationService {
    public async validate(em: EntityManager, data: BlueprintDataDto): Promise<BlueprintValidationResultDto> {
        const issues: BlueprintValidationIssueDto[] = [];
        const nodes = Array.isArray(data?.nodes) ? data.nodes : [];
        const edges = Array.isArray(data?.edges) ? data.edges : [];

        if (!nodes.length) {
            issues.push({ severity: 'error', code: 'empty', message: 'The blueprint has no nodes.' });
        }

        const moduleIds = [...new Set(nodes.map((node) => node.moduleId))];
        const modules = await em.find(
            PipelineModuleEntity,
            { id: { $in: moduleIds } },
            { populate: ['inputTypeSchema', 'outputTypeSchema'] },
        );
        const schemas = new Map<string, ModuleSchemas>(
            modules.map((module) => [
                module.id,
                {
                    type: module.type,
                    input: module.inputTypeSchema?.$.jsonSchema,
                    output: module.outputTypeSchema?.$.jsonSchema,
                },
            ]),
        );

        const nodeIds = new Set<number>();

        for (const node of nodes) {
            if (nodeIds.has(node.id)) {
                issues.push({
                    severity: 'error',
                    code: 'duplicate-node-id',
                    nodeId: node.id,
                    message: `Node id ${node.id} is used twice.`,
                });
            }

            nodeIds.add(node.id);

            if (!schemas.has(node.moduleId)) {
                issues.push({
                    severity: 'error',
                    code: 'unknown-module',
                    nodeId: node.id,
                    message: `Module "${node.moduleId}" does not exist. Available: ${(await this.allModuleIds(em)).join(', ')}.`,
                });
            }
        }

        const edgeIds = new Set<number>();
        const incoming = new Map<number, Set<string>>();

        for (const edge of edges) {
            if (edgeIds.has(edge.id)) {
                issues.push({
                    severity: 'error',
                    code: 'duplicate-edge-id',
                    edgeId: edge.id,
                    message: `Edge id ${edge.id} is used twice.`,
                });
            }

            edgeIds.add(edge.id);
            const source = nodes.find((node) => node.id === edge.source);
            const target = nodes.find((node) => node.id === edge.target);

            if (!source || !target) {
                issues.push({
                    severity: 'error',
                    code: 'dangling-edge',
                    edgeId: edge.id,
                    message: `Edge ${edge.id} connects node ${edge.source} → ${edge.target}, but ${!source ? edge.source : edge.target} does not exist.`,
                });
                continue;
            }

            if (edge.source === edge.target) {
                issues.push({
                    severity: 'error',
                    code: 'self-loop',
                    edgeId: edge.id,
                    message: `Edge ${edge.id} connects node ${edge.source} to itself.`,
                });
            }

            incoming.set(edge.target, (incoming.get(edge.target) ?? new Set()).add(edge.targetHandle));

            const sourceSchema = schemas.get(source.moduleId);
            const targetSchema = schemas.get(target.moduleId);

            if (!sourceSchema || !targetSchema) {
                continue;
            }

            const sourceProperty = this.handleSchema('output', source, sourceSchema.output, edge.sourceHandle);
            const targetProperty = this.handleSchema('input', target, targetSchema.input, edge.targetHandle);

            if (sourceProperty === null) {
                issues.push({
                    severity: 'error',
                    code: 'unknown-output',
                    edgeId: edge.id,
                    nodeId: source.id,
                    message: `"${source.moduleId}" has no output "${edge.sourceHandle}". Outputs: ${this.handleNames(sourceSchema.output, SPECIAL_OUTPUT_HANDLES).join(', ')}.`,
                });
            }

            if (targetProperty === null) {
                issues.push({
                    severity: 'error',
                    code: 'unknown-input',
                    edgeId: edge.id,
                    nodeId: target.id,
                    message: `"${target.moduleId}" has no input "${edge.targetHandle}". Inputs: ${this.handleNames(targetSchema.input, SPECIAL_INPUT_HANDLES).join(', ')}.`,
                });
            }

            if (sourceProperty && targetProperty && !this.typesCompatible(sourceProperty, targetProperty)) {
                issues.push({
                    severity: 'error',
                    code: 'type-mismatch',
                    edgeId: edge.id,
                    message: `Edge ${edge.id}: output "${edge.sourceHandle}" (${String(sourceProperty.type)}) does not fit input "${edge.targetHandle}" (${String(targetProperty.type)}).`,
                });
            }
        }

        for (const node of nodes) {
            const schema = schemas.get(node.moduleId);

            if (!schema?.input) {
                continue;
            }

            const constants = node.constantInputData ?? {};
            const connected = incoming.get(node.id) ?? new Set();

            for (const required of schema.input.required ?? []) {
                if (!(required in constants) && !connected.has(required)) {
                    issues.push({
                        severity: 'error',
                        code: 'missing-input',
                        nodeId: node.id,
                        message: `Node ${node.id} (${node.moduleId}) needs input "${required}": connect an edge to it or set it in constantInputData.`,
                    });
                }
            }

            for (const key of Object.keys(constants)) {
                if (
                    !schema.input.properties?.[key] &&
                    key !== CUSTOM_HANDLE_KEYS.input &&
                    key !== CUSTOM_HANDLE_KEYS.output &&
                    key !== 'code'
                ) {
                    issues.push({
                        severity: 'warning',
                        code: 'unknown-constant',
                        nodeId: node.id,
                        message: `Node ${node.id}: constantInputData.${key} is not an input of ${node.moduleId} and is ignored.`,
                    });
                }
            }

            issues.push(...this.checkTriggerOptions(node.id, node.moduleId, constants));
        }

        if (
            nodes.length &&
            !nodes.some((node) => schemas.get(node.moduleId)?.type === PipelineModuleTypeEnum.TRIGGER)
        ) {
            issues.push({
                severity: 'warning',
                code: 'no-trigger',
                message: 'No trigger node: the blueprint only runs when an execution is created by hand.',
            });
        }

        const cycle = this.findCycle(
            nodes.map((n) => n.id),
            edges,
        );

        if (cycle) {
            issues.push({
                severity: 'error',
                code: 'cycle',
                message: `The blueprint has a cycle: ${cycle.join(' → ')}.`,
            });
        }

        return { valid: !issues.some((issue) => issue.severity === 'error'), issues };
    }

    private async allModuleIds(em: EntityManager): Promise<string[]> {
        return (await em.find(PipelineModuleEntity, {}, { fields: ['id'] })).map((m) => m.id);
    }

    /** Schema of a handle; `undefined` = exists but untyped (special/custom), `null` = does not exist. */
    private handleSchema(
        kind: 'input' | 'output',
        node: { constantInputData?: Record<string, unknown> },
        schema: JSONSchema7 | undefined,
        handle: string,
    ): JSONSchema7 | undefined | null {
        if ((kind === 'input' ? SPECIAL_INPUT_HANDLES : SPECIAL_OUTPUT_HANDLES).has(handle)) {
            return undefined;
        }

        const custom = node.constantInputData?.[CUSTOM_HANDLE_KEYS[kind]];

        if (Array.isArray(custom) && custom.includes(handle)) {
            return undefined;
        }

        if (!schema) {
            return undefined;
        }

        const property: JSONSchema7Definition | undefined = schema.properties?.[handle];

        return property === undefined ? null : typeof property === 'object' ? property : undefined;
    }

    private handleNames(schema: JSONSchema7 | undefined, special: Set<string>): string[] {
        return [...Object.keys(schema?.properties ?? {}).filter((key) => !special.has(key))];
    }

    /** Same rule as the editor: equal types, or anything into an array input (inputs merge into arrays). */
    private typesCompatible(source: JSONSchema7, target: JSONSchema7): boolean {
        return !source.type || !target.type || source.type === target.type || target.type === 'array';
    }

    private checkTriggerOptions(
        nodeId: number,
        moduleId: string,
        constants: Record<string, unknown>,
    ): BlueprintValidationIssueDto[] {
        if (!moduleId.startsWith('common-pipeline-triggers:local-file-trigger')) {
            return [];
        }

        const issues: BlueprintValidationIssueDto[] = [];

        if (!Array.isArray(constants['globPatterns'])) {
            issues.push({
                severity: 'error',
                code: 'invalid-trigger',
                nodeId,
                message: 'globPatterns must be an array of glob strings (may be empty).',
            });
        }

        for (const pattern of Array.isArray(constants['contentPatterns']) ? constants['contentPatterns'] : []) {
            try {
                new RegExp(String(pattern));
            } catch (error) {
                issues.push({
                    severity: 'error',
                    code: 'invalid-trigger',
                    nodeId,
                    message: `contentPatterns entry ${String(pattern)} is not a valid regular expression: ${(error as Error).message}`,
                });
            }
        }

        return issues;
    }

    private findCycle(nodeIds: number[], edges: { source: number; target: number }[]): number[] | undefined {
        const state = new Map<number, 'visiting' | 'done'>();
        const stack: number[] = [];

        const visit = (id: number): number[] | undefined => {
            if (state.get(id) === 'done') return undefined;
            if (state.get(id) === 'visiting') return [...stack.slice(stack.indexOf(id)), id];

            state.set(id, 'visiting');
            stack.push(id);

            for (const edge of edges.filter((e) => e.source === id)) {
                const cycle = visit(edge.target);
                if (cycle) return cycle;
            }

            stack.pop();
            state.set(id, 'done');
            return undefined;
        };

        for (const id of nodeIds) {
            const cycle = visit(id);
            if (cycle) return cycle;
        }

        return undefined;
    }
}
